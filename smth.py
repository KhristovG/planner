# Альтернативная версия с ручной сборкой графа (для обучения)
def create_financial_advisor_manual():
    """Создать агента вручную через LangGraph (для понимания архитектуры)."""
    from langgraph.graph import StateGraph, MessagesState, END
    from langgraph.prebuilt import ToolNode
    from langchain_core.messages import HumanMessage
    from langchain_openai import ChatOpenAI
    
    # Инициализация модели
    llm = ChatOpenAI(model="gpt-4o", temperature=0)  # ЗАГЛУШКА
    llm_with_tools = llm.bind_tools(ALL_TOOLS)
    
    # Определение узла агента
    def agent_node(state: MessagesState):
        """Узел LLM — принимает решение о действиях."""
        response = llm_with_tools.invoke(state["messages"])
        return {"messages": [response]}
    
    # Функция для определения следующего шага
    def should_continue(state: MessagesState):
        """Решить, продолжать ли выполнение инструментов."""
        last_message = state["messages"][-1]
        if last_message.tool_calls:
            return "tools"
        return END
    
    # Сборка графа
    workflow = StateGraph(MessagesState)
    
    # Добавление узлов
    workflow.add_node("agent", agent_node)
    workflow.add_node("tools", ToolNode(ALL_TOOLS))
    
    # Добавление рёбер
    workflow.set_entry_point("agent")
    workflow.add_conditional_edges("agent", should_continue, ["tools", END])
    workflow.add_edge("tools", "agent")
    
    # Компиляция
    return workflow.compile()


