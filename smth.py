# =============================================================================

@tool
def get_stock_quotes(tickers: List[str]) -> str:
    """Получить текущие котировки акций по тикерам.
    
    Возвращает актуальные цены и базовую статистику.
    
    Args:
        tickers: Список тикеров акций (например, ['SBER', 'GAZP'])
        
    Returns:
        Текущие котировки с ценами и изменениями
    """
    # ЗАГЛУШКА: В реальном коде здесь будет вызов API
    mock_data = {
        "SBER": {"price": 285.50, "change": +2.5, "volume": "45M"},
        "GAZP": {"price": 142.30, "change": -1.2, "volume": "12M"},
        "YNDX": {"price": 3200.00, "change": +3.1, "volume": "2M"},
        "LKOH": {"price": 7100.00, "change": +0.5, "volume": "800K"},
        "AAPL": {"price": 178.50, "change": +1.2, "volume": "55M"},
        "GOOGL": {"price": 141.00, "change": -0.3, "volume": "22M"},
        "TSLA": {"price": 245.00, "change": +4.5, "volume": "98M"},
    }
    
    result = "КОТИРОВКИ АКЦИЙ\n" + "=" * 50 + "\n"
    for ticker in tickers:
        if ticker in mock_data:
            data = mock_data[ticker]
            change_sign = "+" if data["change"] >= 0 else ""
            result += f"""
    {ticker}:
      Цена: ${data['price']}
      Изменение: {change_sign}{data['change']}%
      Объём: {data['volume']}
    """
        else:
            result += f"\n    {ticker}: Тикер не найден\n"
    
    return result


